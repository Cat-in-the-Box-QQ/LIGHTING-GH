-- supabase/schema.sql
-- ตารางที่เว็บ LIGHTING-GH ใช้ + Row Level Security policy
-- วิธีใช้: เปิด Supabase Dashboard -> SQL Editor -> วางไฟล์นี้ทั้งไฟล์ -> Run
-- รันซ้ำได้ปลอดภัย (ใช้ IF NOT EXISTS ทั้งหมด)
--
-- หมายเหตุเรื่อง RLS:
--   เว็บนี้เป็น static site ที่เรียก Supabase ตรงจากเบราว์เซอร์ ด้วย anon/publishable key
--   ถ้า "ไม่" สร้าง policy ด้านล่างไว้ RLS จะบล็อกหมด ทำให้เว็บอ่านข้อมูลได้ 0 แถว
--   แล้วระบบจะถอยกลับไปใช้ data/*.json (โหมด local) ซึ่งเป็นอาการที่เหมือน
--   "admin ไม่ทำงาน / ข้อมูลไม่ซิงก์"

-- ============================ fixtures ============================
create table if not exists public.fixtures (
  id                 bigint generated by default as identity primary key,
  brand              text,
  model              text,
  category           text,
  type               text,
  power              numeric,
  power_raw          text,
  weight             numeric,
  weight_raw         text,
  lux                text,
  lumens             text,
  beam               text,
  wireless           text,
  white_light        text,
  color              text,
  color_tag_style    text,
  ip                 text,
  battery            text,
  stock              text,
  stock_count        numeric,
  stock_note         text,
  units_per_set      numeric,
  set_count_in_stock numeric,
  dimensions         text,
  image              text,
  pdf_page           bigint,
  -- text[] อ่านง่ายสุดใน Supabase; โค้ดรองรับทั้ง array, jsonb และ text ธรรมดา
  accessories        text[] default '{}',
  compatible_text    text,
  hidden             boolean default false,
  reserved           numeric default 0,
  in_use             numeric default 0,
  remaining          numeric default 0,
  updated_at         timestamptz default now()
);

