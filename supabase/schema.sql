-- ============================ accessories ============================
create table if not exists public.accessories (
  id             bigint generated by default as identity primary key,
  name           text,
  brand          text,
  category       text,
  stock          text,
  image          text,
  pdf_page       bigint,
  -- เก็บ id ของ fixture ที่ใช้ร่วมกันได้
  compatible_with bigint[] default '{}',
  hidden         boolean default false,
  updated_at     timestamptz default now()
);

alter table public.accessories add column if not exists name            text;
alter table public.accessories add column if not exists brand           text;
alter table public.accessories add column if not exists category        text;
alter table public.accessories add column if not exists stock           text;
alter table public.accessories add column if not exists image           text;
alter table public.accessories add column if not exists pdf_page        bigint;
alter table public.accessories add column if not exists compatible_with bigint[] default '{}';
alter table public.accessories add column if not exists hidden          boolean default false;
alter table public.accessories add column if not exists updated_at      timestamptz default now();

create index if not exists accessories_name_idx on public.accessories (name);

-- ============================ Row Level Security ============================
alter table public.fixtures    enable row level security;
alter table public.accessories enable row level security;

-- อ่านได้ทุกคน (รวมผู้เยี่ยมชมที่ยังไม่ login)
drop policy if exists "public read fixtures" on public.fixtures;
create policy "public read fixtures"
  on public.fixtures for select
  using (true);

drop policy if exists "public read accessories" on public.accessories;
create policy "public read accessories"
  on public.accessories for select
  using (true);

-- เขียนได้เฉพาะผู้ที่ login ผ่าน Supabase Auth แล้ว
-- (หน้า admin บังคับ login ด้วย email + password ก่อนจึงจะเห็นปุ่มแก้ไข/ซ่อน/ลบ)
drop policy if exists "auth write fixtures" on public.fixtures;
create policy "auth write fixtures"
  on public.fixtures for all
  to authenticated
  using (true)
  with check (true);

drop policy if exists "auth write accessories" on public.accessories;
create policy "auth write accessories"
  on public.accessories for all
  to authenticated
  using (true)
  with check (true);

-- ============================ ตรวจผลหลังรัน ============================
-- ถ้า 2 บรรทัดนี้คืนค่า > 0 แปลว่าตารางพร้อมใช้งานแล้ว
select 'fixtures' as table_name, count(*) as rows from public.fixtures
union all
select 'accessories', count(*) from public.accessories;
